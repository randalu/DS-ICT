// Playwright CLI run-code fixture; requires the disposable review server on 8139.
async (page) => {
    const checks = [], errors = [], failures = [], base = 'http://127.0.0.1:8139';
    const check = (ok, label) => { if (!ok) throw new Error(label); checks.push(label); };
    await page.unrouteAll();
    page.on('pageerror', error => errors.push(error.message));
    page.on('response', response => { if (response.status() >= 400) failures.push(response.status() + ' ' + response.url()); });
    await page.setViewportSize({width:1440,height:1000});
    await page.goto(base + '/__fixture');
    await page.goto(base + '/admin/tour_form.php?id=101');
    check(await page.locator('.faq-question').first().inputValue() === 'How can I plan a private visit?', 'Legacy q/a questions render in normal editor');
    check(await page.locator('.faq-answer').first().inputValue() === 'Discuss your route with our team.', 'Legacy q/a answers render in normal editor');
    await page.goto(base + '/admin/seo_manager.php');
    await page.locator('#seo-list button').first().click();
    await page.locator('[data-plan="primary_phrase"]').waitFor();
    check(await page.locator('[data-plan="primary_phrase"]').inputValue() === 'Keep existing primary', 'Existing keyword plan loaded');
    await page.getByRole('button',{name:'Open keyword research',exact:true}).click();
    const review = page.locator('#seo-research-output').getByRole('button',{name:'Review & apply keyword suggestions',exact:true});
    check(await review.isVisible(), 'Partial research has review action without primary phrase');
    check(await page.locator('#seo-research-output').textContent().then(text=>!text.includes('supporting phrases')), 'Empty supporting phrase heading omitted');
    await review.click();
    const dialog = page.getByRole('dialog');
    check(await dialog.locator('[data-review-plan="primary_phrase"]').inputValue() === '', 'Review explicitly shows missing primary phrase');
    check(!(await dialog.locator('[data-approve-plan="primary_phrase"]').isChecked()), 'Missing primary phrase is not pre-approved');
    check(await page.locator('[data-plan="intent"]').inputValue() === 'Old intent', 'Opening review does not fill editor');
    await dialog.getByRole('button',{name:'Cancel review',exact:true}).click();
    check(await page.locator('[data-plan="intent"]').inputValue() === 'Old intent', 'Cancel preserves existing fields');
    await review.click();
    await dialog.locator('[data-approve-plan="notes"]').uncheck();
    await dialog.getByRole('button',{name:'Apply approved suggestions to editor',exact:true}).click();
    check(await page.locator('[data-plan="primary_phrase"]').inputValue() === 'Keep existing primary', 'Blank primary suggestion preserves existing phrase');
    check(await page.locator('[data-plan="supporting_phrases"]').inputValue() === 'Keep supporting phrase', 'Blank supporting suggestions preserve existing phrases');
    check(await page.locator('[data-plan="intent"]').inputValue() === 'Plan an east-coast private travel visit', 'Approved intent fills editor');
    check((await page.locator('[data-plan="questions"]').inputValue()).includes('private itinerary'), 'Approved audience questions fill editor');
    check(await page.locator('[data-plan="notes"]').inputValue() === 'My existing notes', 'Unchecked notes are preserved');
    check(await page.locator('#seo-save-plan').isChecked(), 'Keyword plan selected for later explicit save');
    const stored = await (await page.request.get(base+'/admin/seo_manager_api.php?action=load&type=destination&id=101')).json();
    check(stored.record.plan.intent === 'Old intent', 'Applying suggestions does not save content');
    await page.locator('#seo-editor').getByRole('button',{name:'Review & apply keyword suggestions',exact:true}).click();
    await dialog.getByRole('button',{name:'Apply approved suggestions to editor',exact:true}).click();
    check((await page.locator('[data-plan="notes"]').inputValue()).includes('Current seasonal conditions are unconfirmed.'), 'Notes can be filled from research uncertainties');
    await page.locator('#seo-editor').getByRole('button',{name:'Review & apply keyword suggestions',exact:true}).click();
    await dialog.locator('[data-review-plan="intent"]').evaluate(el=>{el.value='x'.repeat(501);});
    await dialog.getByRole('button',{name:'Apply approved suggestions to editor',exact:true}).click();
    check(await dialog.getByRole('status').textContent().then(text=>text.includes('exceeds its limit')), 'Over-limit suggestions stay in review');
    check(await page.locator('[data-plan="intent"]').inputValue() === 'Plan an east-coast private travel visit', 'Invalid approval makes no partial editor changes');
    await dialog.getByRole('button',{name:'Cancel review',exact:true}).click();
    await page.setViewportSize({width:390,height:844});
    await page.locator('#seo-editor').getByRole('button',{name:'Review & apply keyword suggestions',exact:true}).click();
    check(await dialog.evaluate(el=>el.getBoundingClientRect().right<=innerWidth), 'Mobile review fits viewport');
    await page.screenshot({path:'output/seo-manager/keyword-review-mobile.png'});
    await page.keyboard.press('Escape');
    check(await dialog.count() === 0, 'Escape cancels keyword review');
    check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth), 'Mobile editor has no horizontal overflow');
    let calls = 0;
    await page.route('**/admin/seo_manager_api.php',async route=>{
        if(route.request().method()!=='POST')return route.continue();
        calls++;
        const isPlatform = calls === 1;
        await route.fulfill({json:{result:{id:999,kind:isPlatform?'guidance':'keywords',content_type:isPlatform?'':'destination',content_id:isPlatform?0:999,
            market:'International',created_at:'2026-10-16 00:00:00',stale:false,data:{primary_phrase:'Wrong page phrase',intent:'Wrong intent',market:'International',sources:[]}}}});
    });
    await page.getByRole('button',{name:'Research',exact:true}).click();
    await page.getByRole('button',{name:'Refresh SEO guidance',exact:true}).click();
    await page.locator('#seo-research-output').getByText('General SEO guidance is for the Principles review; it does not fill a page’s keyword plan.').waitFor();
    check(await page.locator('#seo-research-output').getByRole('button',{name:'Review & apply keyword suggestions',exact:true}).count()===0, 'General guidance cannot populate page keywords');
    await page.getByRole('button',{name:'Research selected page’s keywords',exact:true}).click();
    await page.locator('#seo-research-output').getByText('Wrong page phrase',{exact:true}).waitFor();
    check(await page.locator('#seo-research-output').getByRole('button',{name:'Review & apply keyword suggestions',exact:true}).count()===0, 'Another page’s research cannot be approved for current page');
    check(errors.length===0,'No uncaught browser errors: '+errors.join('; '));
    check(failures.length===0,'No unexpected HTTP failures: '+failures.join('; '));
    console.log(JSON.stringify({checks})); return checks;
}
